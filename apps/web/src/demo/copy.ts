import type { Locale } from "./types";
export function words(
  locale: Locale,
  en: string,
  fr: string,
  ar: string,
): string {
  return { en, fr, ar }[locale];
}
export function money(value: number, locale: Locale): string {
  return `${new Intl.NumberFormat(locale === "ar" ? "ar-MA" : locale === "fr" ? "fr-MA" : "en-GB", { maximumFractionDigits: 0 }).format(value)} ${locale === "ar" ? "درهم" : "DH"}`;
}
